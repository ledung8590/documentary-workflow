"""Write the music-bed block of sound.txt: one MOODS.md group per section, 2-3 min beds cut at sentence ends,
no file reused within 25 min, plus music dips under key lines.  PY qa/music_plan.py > qa/music.txt"""
import json, subprocess
from pathlib import Path

D = Path(__file__).resolve().parents[1]
ROOT = D.parents[1]
T = json.loads((D / 'voice' / 'timing.json').read_text(encoding='utf-8'))
S = T['sentences']; ids = sorted(S, key=lambda k: S[k]['start'])
G = {  # MOODS.md six groups (beds whose files exist)
    1: ['milintro/el_01', 'milintro/el_02', 'milsuspense/el_03'],
    2: ['milsuspense/el_01', 'darkdrone/el_01', 'spyintrigue/el_02', 'milsuspense/el_04', 'darkdrone/el_02', 'milsuspense/el_02',
        'spyintrigue/el_03', 'milsuspense/el_05', 'milsuspense/el_06'],
    3: ['miltech/el_01', 'strategy/el_01', 'miltech/el_04', 'strategy/el_02', 'miltech/el_05', 'strategy/el_03', 'miltech/el_06'],
    4: ['warstrings/el_03', 'spysuspense/el_02', 'spychase/el_04', 'warstrings/el_04', 'spysuspense/el_06', 'spychase/el_01',
        'warstrings/el_02', 'spysuspense/el_03', 'spychase/el_02', 'spysuspense/el_05', 'warstrings/el_01'],
    5: ['somber/el_03', 'lament/el_03', 'europe1870/el_01', 'somber/el_01', 'lament/el_01', 'europe1870/el_02', 'somber/el_02',
        'lament/el_02'],
    6: ['milverdict/el_01', 'resolve/el_01', 'milverdict/el_02', 'resolve/el_02', 'milverdict/el_03'],
}
GAIN = {1: -20.5, 2: -20.5, 3: -21, 4: -20.5, 5: -21.5, 6: -21}  # 20-22 dB under the voice (2026-11-14), measured with qa/music_level.py
SECTIONS = [  # EDIT PER FILM: (first sentence of each section, MOODS.md group) from STORY.md chapters; this list is the space-race film's
    ('S001', 1), ('S032', 2), ('S110', 3), ('S128', 2), ('S150', 3), ('S172', 5), ('S186', 3), ('S201', 2), ('S240', 3),
    ('S273', 4), ('S290', 3), ('S329', 4), ('S357', 3), ('S392', 4), ('S444', 2), ('S517', 5), ('S533', 3), ('S546', 2),
    ('S581', 3), ('S612', 5), ('S639', 2), ('S679', 6), ('S696', 5), ('S700', 6)]
LEN = {}
for g in G.values():
    for b in g:
        LEN[b] = float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0',
                                       str(ROOT / 'assets' / 'music' / (b + '.mp3'))], capture_output=True, text=True).stdout)
last_used, ptr, out, prev = {}, {g: 0 for g in G}, [], None
starts = [ids.index(s) for s, _ in SECTIONS] + [len(ids)]
for n, (s0, g) in enumerate(SECTIONS):
    i, end = starts[n], starts[n + 1]
    while i < end:
        t0 = S[ids[i]]['start']
        for _ in range(len(G[g])):  # next bed of the group not used in the last 25 min
            b = G[g][ptr[g] % len(G[g])]; ptr[g] += 1
            if t0 - last_used.get(b, -1e9) > 900 and b != prev:
                break
        cap = LEN[b] - 8
        rem = S[ids[end - 1]]['end'] - t0
        target = rem / max(1, -(-rem // 118)) if rem > cap else cap  # even beds of ~100-118 s, no stubs
        j = i
        while j + 1 < end and S[ids[j + 1]]['end'] - t0 < min(cap, target + 10):
            j += 1
        if j + 1 < end and S[ids[end - 1]]['end'] - S[ids[j]]['end'] < 40 and S[ids[end - 1]]['end'] - t0 < LEN[b] - 3:
            j = end - 1
        last_used[b] = S[ids[j]]['end']; prev = b
        a = f'{ids[i]}-3.4' if i == 0 else f'{ids[i - 1]}$+0.3'
        z = ids[j + 1] if j + 1 < len(ids) else f'{ids[j]}$+2.5'
        out.append(f'{a} .. {z} | music/{b} | {GAIN[g]}   # {S[ids[j]]["end"] - t0:.0f} s, group {g}')
        i = j + 1
DIPS = ['S009', 'S013', 'S016', 'S077', 'S124', 'S145', 'S173', 'S333', 'S435', 'S515', 'S702', 'S705', 'S707']
print('# music beds (generated by qa/music_plan.py; six MOODS.md groups per section, no drums)')
print('\n'.join(out))
print('# music dips under key lines (reveals, holds, closing question)')
for d in DIPS:
    print(f'{d} .. {d}$ | dip | -10')

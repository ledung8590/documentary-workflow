"""Template: templates/archival/gen_sound.py (copied by `doc.py plan JOB`). Per film, set TITLE_SCENE, FIRE and SUBSCRIBE_AT below.

Write sound_scenes.txt (card SFX + SFX for every flash, volley, shot, clash and fall drawn in a scene, from scenes/events-*.txt
written on a 10 s scale) and the subscribe sequence. Music beds stay in sound.txt (hand-planned, no drums).
Run after `plan.py durations` and the scene builds:  PY gen_sound.py

Levels: every SFX is set RELATIVE TO THE VOICE, from the file's own loudness (user review 2026-11-02: "tất cả fx đều bị
to hơn voice" — the library files differ by up to 35 dB, so a fixed gain per type was wrong). `under` = how many dB the
loudest 400 ms of the SFX sits below the voice's median 400 ms level while speaking."""
import json
import subprocess
import numpy as np
import plan

TITLE_SCENE = 'a-title'   # the JS title scene: its first `thud` event becomes the title hit stack
SUBSCRIBE_AT = ''         # anchor of the subscribe click word, e.g. 'S009 "abonnieren"' / 'S004 "subscribe"' / 'S006 "đăng ký"'
# real film clips whose own picture fires: {'v-tag#K': [(clip seconds, 'cannon/el_01', under dB, dur)]}, measured on the clip
FIRE = {}

D = plan.D
out = ['# generated by gen_sound.py - do not edit by hand']


def _pcm(p, t0=None, dur=None, hp=False):
    a = ['ffmpeg', '-v', 'error'] + (['-ss', str(t0), '-t', str(dur)] if t0 is not None else []) + ['-i', str(p)] +         (['-af', 'highpass=f=400:poles=2,highpass=f=400:poles=2'] if hp else []) + ['-ac', '1', '-ar', '16000', '-f', 'f32le', '-']
    return np.frombuffer(subprocess.run(a, capture_output=True).stdout, np.float32)


def _mom(x):  # 400 ms momentary level (dB RMS), 100 ms steps
    w, s = 6400, 1600
    if len(x) < w:
        x = np.pad(x, (0, w - len(x)))
    return np.array([10 * np.log10(np.mean(x[i:i + w] ** 2) + 1e-12) for i in range(0, len(x) - w + 1, s)])


_v = _mom(_pcm(D / 'voice' / 'voice.wav', 0, 900))
VOICE = float(np.median(_v[_v > _v.max() - 25]))
_vh = _mom(_pcm(D / 'voice' / 'voice.wav', 0, 900, hp=True))
VOICE_HI = float(np.median(_vh[_v > _v.max() - 25]))  # the voice above 400 Hz, where laptops and earbuds hear
_lvl = {}


# Levels in LUFS on both sides (memory sfx-level-relative-to-voice; film 89 moved archival off the 400 ms peak method, which
# left story 51's risers 15-18 dB under and film 75's hits over the voice): gain = voice integrated LUFS - LUFS of the section
# of the file that plays (0..dur) - UNDER[type]. Card hits 3 dB under, risers 4, whoosh/drop 6; types not listed keep `under`.
UNDER = {'cardslam': 5, 'impact': 4, 'chapterhit': 6, 'titlehit': 5, 'stamp': 5, 'reveal': 7, 'navalblast': 3, 'missilelaunch': 3,
         'sublaunch': 3, 'icecrack': 4, 'revswell': 6, 'riser': 4, 'whoosh': 8, 'subdrop': 9, 'steamburst': 6, 'klaxon': 6,
         'sonarping': 8, 'mapping': 8, 'typewriter': 10, 'typebell': 8, 'mouseclick': 6, 'subscribed': 5, 'notifybell': 7}
# Cards stack 2-4 of these at once (chapter: whoosh + chapterhit + subdrop + cardslam): the per-file offsets above put the
# STACK about 3 dB under the voice, measured on the sfx stem (film 89: single-file offsets of 3 made the chapter stack equal the voice).


def _file(rel):
    return plan.asset('sfx/' + rel).replace('../../', str(plan.ROOT) + '/')


def _lufs(f, dur=None, _c={}):
    import re as _re
    if (f, dur) not in _c:
        o = subprocess.run(['ffmpeg', '-hide_banner', '-nostats', *(['-t', f'{dur:.3f}'] if dur else []), '-i', f, '-af', 'ebur128',
                            '-f', 'null', '-'], capture_output=True, text=True, encoding='utf-8', errors='replace').stderr
        v = _re.findall(r'I:\s+(-?[\d.]+) LUFS', o)
        _c[(f, dur)] = float(v[-1]) if v else -70.0
    return _c[(f, dur)]


def _clipped(f, _c={}):  # % of samples at full scale: hard-clipped ElevenLabs files crackle at any gain
    if f not in _c:
        x = _pcm(f); _c[f] = float((np.abs(x) > 0.97).mean() * 100) if len(x) else 0.0
    return _c[f]


def _clean(rel):
    """The least-clipped file of the type when `rel` is clipped over 1 % (subdrop/el_01 is 49 %)."""
    if _clipped(_file(rel)) <= 1.0:
        return rel
    name = rel.split('/')[0]
    alts = [f'{name}/{q.stem}' for q in (plan.ROOT / 'assets' / 'sfx' / name).glob('el_*.*') if q.suffix in ('.mp3', '.wav')]
    best = min(alts, key=lambda r: _clipped(_file(r)))
    if _clipped(_file(best)) > 1.0:
        print(f'!! sfx {best} is {_clipped(_file(best)):.1f} % clipped (crackles): regenerate it')
    return best


VOICE_LUFS = _lufs(str(D / 'voice' / 'voice.wav'))


def gain_for(rel, under, dur=None, force=False):  # force: this line's own offset beats the UNDER table
    return round(max(-40.0, min(12.0, VOICE_LUFS - _lufs(_file(rel), dur) - (under if force else UNDER.get(rel.split('/')[0], under)))), 1)


def add(t, rel, under, dur, force=False):
    rel = _clean(rel)
    out.append(f'START+{t:.3f} | sfx/{rel} | {gain_for(rel, under, dur, force)} | {dur}')


# ---- cards
for r in plan.lines('overlays.txt'):
    a, b = [x.strip() for x in r[0].split('..')]
    t0 = plan.resolve(a)
    kind = r[1]
    props = json.loads(r[2]) if len(r) > 2 and r[2] else {}
    if kind == 'chapter':
        add(t0 - 0.4, 'whoosh/el_01', 12, 1.5); add(t0, 'chapterhit/el_01', 6, 3)
        add(t0, 'subdrop/el_01', 9, 3); add(t0, 'cardslam/el_01', 1, 1.5)
    elif kind == 'title_card':  # overlay title (no JS title scene): rev swell into a title hit (WORKFLOW stage 8)
        if not TITLE_SCENE:
            add(t0 - 2.0, 'revswell/el_01', 8, 2.2); add(t0, 'titlehit/el_03', 5, 4); add(t0, 'cardslam/el_01', 1, 1.5)
    elif kind == 'question':
        add(t0, 'cardslam/el_01', 1, 1.5); add(t0, 'impact/el_01', 7, 3)
    elif kind == 'quote':
        n = sum(len(x) for x in props.get('lines', [props.get('text', '')])); dur = n / props.get('cps', 16)
        add(t0 + 0.7, 'typewriter/el_03', 10, round(dur, 2)); add(t0 + 0.7 + dur, 'typebell/el_01', 10, 1.5)
    elif kind == 'stat':
        add(t0, 'cardslam/el_01', 2, 1.5)
        for k, it in enumerate(props.get('items', [])):
            at = it.get('at', 0.6 + 0.45 * k)
            at = plan.resolve(at) - t0 if isinstance(at, str) else at
            add(t0 + at, 'reveal/el_01', 10, 1.2); add(t0 + at, 'cardslam/el_01', 1, 1.5)  # reveal is sub-bass: cardslam is the part laptops hear
    elif kind == 'date_tag':
        add(t0 + 0.3, 'mapping/el_01', 14, 1.5)

# ---- scene events: (10 s-scale seconds | kind | note) -> SFX on the exact frame. Black-powder era sounds.
MAP = {'gunshot': ('musket/el_01', 10, 1.5), 'volley': ('rifles/el_01', 8, 2.5), 'cannon': ('cannon/el_01', 7, 2.5),
       'burst': ('shellburst/el_01', 8, 2.5), 'clash': ('sabre/el_01', 11, 1.5), 'fall': ('knockfloor/el_01', 13, 1.2),
       'thud': ('stamp/el_02', 12, 1.2), 'drum': ('drum/el_01', 12, 2), 'thunder': ('thunder/el_01', 8, 3),
       'spearvolley': ('spearvolley/el_01', 9, 2.5), 'spearhit': ('spearhit/el_01', 10, 1.2), 'swordclash': ('swordclash/el_01', 10, 1.8),
       'warcry': ('warcry/el_01', 10, 3.5), 'firecrackle': ('firecrackle/el_01', 12, 4), 'rainforest': ('rainforest/el_01', 14, 6),
       # WWII air war (film 90)
       'cannon37': ('cannon37/el_01', 6, 1.8), 'mg': ('mg50/el_01', 8, 1.6), 'dive': ('planedive/el_02', 8, 3), 'flyby': ('planeflyby/el_01', 8, 3),
       'whoosh': ('whoosh/el_01', 12, 1.5), 'hit': ('impact/el_01', 7, 2.5),
       'clock': ('clock/el_01', 12, 6), 'gallop': ('gallop/el_01', 12, 4), 'rain': ('rainroof/el_01', 14, 6),
       'steam': ('steamburst/el_01', 8, 2.5), 'clang': ('clang/el_01', 9, 1.2), 'crash': ('impact/el_02', 7, 1.5), 'engine': ('enginestart/el_01', 12, 2.5)}
ALT = {'gunshot': ['musket/el_01', 'gunshot/el_03'], 'cannon': ['cannon/el_01', 'cannon/el_02', 'artillery/el_01']}
GAP = {'gunshot': 0.6}  # thin out dense fire: one shot per 0.6 s reads as a firefight, not a wall of noise
sd = json.loads((D / 'scenes' / 'src' / 'durations.json').read_text(encoding='utf-8'))
n_ev = 0
for s in plan.shots():
    k, _, name = s['src'].partition(':')
    if k != 'scene':
        continue
    ev = D / 'scenes' / f'events-{name}.txt'
    if not ev.exists():
        continue
    txt = ev.read_text(encoding='utf-8')
    f = 1.0 if txt.startswith('# REAL') else sd.get(name, 10) / 10   # '# REAL' = already in real scene seconds
    last = {}
    for i, ln in enumerate(txt.splitlines()):
        p = [x.strip() for x in ln.split('|')]
        if len(p) < 2 or p[1] not in MAP:
            continue
        kind = 'thunder' if p[1] == 'thud' and 'thunder' in (p[2] if len(p) > 2 else '').lower() else p[1]
        try:
            t = float(p[0]) * f
        except ValueError:
            continue
        if t >= s['t1'] - s['t0']:
            continue
        if t - last.get(kind, -9) < GAP.get(kind, 0.35):   # a salvo reads as one hit
            continue
        last[kind] = t
        rel, under, dur = MAP[kind]
        if name == TITLE_SCENE and kind == 'thud':  # title card: rev swell into a title hit (WORKFLOW stage 8)
            # title (memory card-sfx-and-music-levels): revswell + whoosh into titlehit + subdrop, with cardslam as the audible mid/high layer
            add(s['t0'] + max(t - 1.2, 0), 'revswell/el_01', 8, 1.6); add(s['t0'] + max(t - 0.4, 0), 'whoosh/el_01', 10, 1.5)
            add(s['t0'] + t, 'subdrop/el_01', 7, 3); add(s['t0'] + t, 'cardslam/el_01', 3, 1.5)
            rel, under, dur = 'titlehit/el_01', 4, 3
        if kind in ALT:
            rel = ALT[kind][n_ev % len(ALT[kind])]
        dur = round(min(dur, s['t1'] - s['t0'] - t + 0.15), 2)  # stop at the cut (render fades the last 0.3 s): no tail into the next shot
        add(s['t0'] + t, rel, under, dur); n_ev += 1

# ---- archival/reenactment film clips: the shot they show (clip seconds of the first visible firing, measured on the clip's own audio)
for s in plan.shots():
    k, _, rest = s['src'].partition(':')
    key = rest if rest in FIRE else rest.split('@')[0]  # 'tag#K@IN' (one cut) wins over 'tag#K' (every cut of that film)
    if k == 'vid' and key in FIRE:
        for at, rel, under, dur in FIRE[key]:
            add(s['t0'] + at, rel, under, round(min(dur, s['t1'] - s['t0'] - at + 0.15), 2))

# ---- typing spans written automatically: every scene that calls L.typed( gets scenes/typing-NAME.txt from `jsscene.mjs --typing`
# (film 76: two typed scenes had no hand-written file and played silent). Rewritten whenever the built scene is newer.
for s in plan.shots():
    k, _, name = s['src'].partition(':')
    js, built, p = D / 'scenes' / 'src' / f'{name}.js', D / 'scenes' / f'{name}.js', D / 'scenes' / f'typing-{name}.txt'
    if k != 'scene' or not js.exists() or 'L.typed(' not in js.read_text(encoding='utf-8') or not built.exists():
        continue
    if p.exists() and p.stat().st_mtime >= built.stat().st_mtime:
        continue
    tmp = D / 'qa' / f'typing-{name}.json'; tmp.parent.mkdir(exist_ok=True)
    subprocess.run(['node', str(plan.ROOT / 'scripts' / 'jsscene.mjs'), str(built), str(tmp), '--typing'], capture_output=True, timeout=600)
    spans = json.loads(tmp.read_text(encoding='utf-8')) if tmp.exists() else []
    f = sd.get(name, 10) / 10  # the file is on the 10 s scale, like the hand-written ones
    p.write_text(''.join(f'{a / f:.3f} {b / f:.3f}' + chr(10) for a, b in spans), encoding='utf-8')
    print(f'typing-{name}.txt: {len(spans)} span(s) from jsscene --typing')

# ---- typed text in JS scenes (scenes/typing-NAME.txt: "start end [dB under the voice]" per line on the 10 s scale)
for s in plan.shots():
    k, _, name = s['src'].partition(':')
    p = D / 'scenes' / f'typing-{name}.txt'
    if k == 'scene' and p.exists():
        f = sd.get(name, 10) / 10
        for ln in p.read_text(encoding='utf-8').splitlines():
            x = ln.replace(',', ' ').split()
            try:
                a, b = float(x[0]) * f, float(x[1]) * f
            except (ValueError, IndexError):
                continue
            if a < s['t1'] - s['t0']:
                add(s['t0'] + a, 'typewriter/el_03', float(x[2]) if len(x) > 2 else 12, round(b - a + 0.08, 2), len(x) > 2)


"""Built-in overlay loops for the studio (Hiệu ứng → Lớp phủ media), generated from render_fx so they carry no licence:
  assets/overlays/bui-xuoc-phim.mp4   dust + scratches on black   (blend: screen)
  assets/overlays/hat-phim.mp4        film grain on mid grey      (blend: overlay / soft_light)
  assets/overlays/loa-sang-am.mp4     warm light leak on black    (blend: screen / add)
  assets/overlays/khung-phim-cu.png   dark rounded film-gate frame (blend: multiply)

  PY scripts/make_overlays.py
"""
import subprocess, sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

sys.path.insert(0, str(Path(__file__).resolve().parent))
import render_fx as FX

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets' / 'overlays'
W, H, FPS, SECS = FX.W, FX.H, 24, 6


def write(name, frame_fn):
    p = OUT / name
    ff = subprocess.Popen(['ffmpeg', '-v', 'error', '-y', '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-s', f'{W}x{H}', '-r', str(FPS), '-i', '-',
                           '-c:v', 'libx264', '-preset', 'medium', '-crf', '20', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', str(p)],
                          stdin=subprocess.PIPE)
    for i in range(FPS * SECS):
        ff.stdin.write(np.clip(frame_fn(i), 0, 255).astype(np.uint8).tobytes())
    ff.stdin.close(); ff.wait()
    print(p)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    black = np.zeros((H, W, 3), np.float32)
    write('bui-xuoc-phim.mp4', lambda i: FX.scratches_dust(black, 0.9, 1.0, i, 11) * 1.4)
    grey = np.full((H, W, 3), 128, np.float32)
    write('hat-phim.mp4', lambda i: FX.grain(grey, 0.9, 1.6, i))
    write('loa-sang-am.mp4', lambda i: FX.light_leak(black, 0.9, 28, 0.6, i / FPS))
    m = Image.new('L', (W, H), 255); d = ImageDraw.Draw(m)
    d.rounded_rectangle((70, 50, W - 70, H - 50), radius=90, fill=0)
    m = m.filter(ImageFilter.GaussianBlur(40))
    frame = Image.merge('RGB', [Image.eval(m, lambda v: 255 - v)] * 3)  # white inside, dark gate edges: multiply
    frame.save(OUT / 'khung-phim-cu.png'); print(OUT / 'khung-phim-cu.png')
    (OUT / 'LICENSES.md').write_text('# Overlay loops\nGenerated by scripts/make_overlays.py from scripts/render_fx.py (own work, no third-party material).\n', encoding='utf-8')


if __name__ == '__main__':
    main()
